"""
predictor.py – Scikit-learn sentiment prediction models.

Two independent tasks:
  binary     : negative  vs  non-negative
  multiclass : positive / neutral / negative

Models: TF-IDF + Logistic Regression  AND  TF-IDF + Random Forest.
Evaluation: stratified CV (when counts allow), accuracy, precision, recall,
            F1, confusion matrix, ROC-AUC (binary only).

IMPORTANT: labels come from Azure AI Language or VADER – machine-generated,
not human-verified ground truth.  Every output says so explicitly.
"""

import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import make_pipeline

# ── Thresholds ────────────────────────────────────────────────────────────────
MIN_UNIQUE = 20          # minimum deduplicated reviews to attempt training
MIN_PER_CLASS = 3        # minimum samples per class (binary or multiclass)
LOW_CONFIDENCE_THRESHOLD = 0.5

LABEL_SOURCE_NOTE = (
    "Labels are machine-generated by Azure AI Language or VADER. "
    "They are NOT human-verified ground truth. "
    "Metrics reflect the model's ability to reproduce those labels."
)

METHOD_LR = (
    "TF-IDF (1-2 grams, sublinear TF) + Logistic Regression (balanced class weights). "
    "Trained on this upload's own machine-generated sentiment labels. "
    "It is an estimate — it learns the labeller's mistakes too."
)
METHOD_RF = (
    "TF-IDF (1-2 grams, sublinear TF) + Random Forest (100 trees, balanced class weights). "
    "Trained on this upload's own machine-generated sentiment labels. "
    "It is an estimate — it learns the labeller's mistakes too."
)


# ── Internal helpers ──────────────────────────────────────────────────────────

def _unique_labeled(results):
    """Deduplicate reviews: one row per unique text, majority label."""
    df = results[["feedback", "sentiment"]].copy()
    df["key"] = df["feedback"].astype(str).str.strip().str.lower()
    rows = []
    for _, g in df.groupby("key"):
        rows.append((str(g["feedback"].iloc[0]), g["sentiment"].mode().iloc[0]))
    return rows


def _binarize(labels):
    """Convert 3-class labels to binary: 'negative' vs 'non-negative'."""
    return np.where(np.array(labels) == "negative", "negative", "non-negative")


def _lr_pipeline():
    return make_pipeline(
        TfidfVectorizer(ngram_range=(1, 2), lowercase=True, sublinear_tf=True),
        LogisticRegression(max_iter=1000, class_weight="balanced"),
    )


def _rf_pipeline():
    return make_pipeline(
        TfidfVectorizer(ngram_range=(1, 2), lowercase=True, sublinear_tf=True),
        RandomForestClassifier(n_estimators=100, class_weight="balanced", random_state=42),
    )


def _cv_metrics(texts, labels, pipeline, n_splits, task):
    """
    Run stratified cross-validation and compute all metrics.
    Returns a dict or raises ValueError if CV cannot run.
    """
    cv = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=42)
    predicted = cross_val_predict(pipeline, texts, labels, cv=cv)
    classes = sorted(set(labels))

    report = classification_report(
        labels, predicted, output_dict=True, zero_division=0
    )
    cm = confusion_matrix(labels, predicted, labels=classes).tolist()

    metrics = {
        "cv_folds": n_splits,
        "cv_accuracy": round(float(accuracy_score(labels, predicted)), 3),
        "precision_macro": round(float(report["macro avg"]["precision"]), 3),
        "recall_macro": round(float(report["macro avg"]["recall"]), 3),
        "f1_macro": round(float(report["macro avg"]["f1-score"]), 3),
        "confusion_matrix": cm,
        "confusion_matrix_labels": classes,
        "per_class": {
            c: {
                "precision": round(float(report[c]["precision"]), 3),
                "recall": round(float(report[c]["recall"]), 3),
                "f1": round(float(report[c]["f1-score"]), 3),
                "support": int(report[c]["support"]),
            }
            for c in classes if c in report
        },
    }

    # ROC-AUC only for binary tasks (needs predict_proba on full fit)
    if task == "binary" and len(classes) == 2:
        try:
            proba = cross_val_predict(
                pipeline, texts, labels, cv=cv, method="predict_proba"
            )
            neg_idx = classes.index("negative")
            roc = roc_auc_score(
                labels, proba[:, neg_idx],
                pos_label="negative"
            )
            metrics["roc_auc"] = round(float(roc), 3)
        except Exception:
            metrics["roc_auc"] = None

    return metrics


def _train_one(texts, labels, task):
    """
    Train LR and RF, evaluate both, return a model-store dict.
    task: 'binary' | 'multiclass'
    """
    classes, counts = np.unique(labels, return_counts=True)
    keep = [c for c, n in zip(classes, counts) if n >= MIN_PER_CLASS]
    dropped = [c for c in classes if c not in keep]

    if len(keep) < 2:
        return None, (
            "Need at least 2 classes with >= %d reviews each. "
            "Currently: %s" % (MIN_PER_CLASS, dict(zip(classes, counts)))
        )

    # Filter to keep-able classes
    mask = np.isin(labels, keep)
    texts_f = [t for t, m in zip(texts, mask) if m]
    labels_f = labels[mask]

    classes_f, counts_f = np.unique(labels_f, return_counts=True)
    n_splits = int(min(5, counts_f.min()))

    store = {
        "task": task,
        "classes": list(classes_f),
        "dropped_classes": [str(c) for c in dropped],
        "unique_reviews": len(texts_f),
        "label_source": LABEL_SOURCE_NOTE,
    }

    for name, pipe_fn, method_note in [
        ("lr", _lr_pipeline, METHOD_LR),
        ("rf", _rf_pipeline, METHOD_RF),
    ]:
        pipe = pipe_fn()
        try:
            cv_metrics = _cv_metrics(texts_f, labels_f, pipe_fn(), n_splits, task)
        except ValueError as exc:
            return None, "CV failed for %s: %s" % (name, str(exc)[:120])

        # Final fit on all data
        pipe.fit(texts_f, labels_f)
        majority_baseline = round(float(counts_f.max() / counts_f.sum()), 3)
        store[name] = {
            "model": pipe,
            "method": method_note,
            "cv_metrics": cv_metrics,
            "majority_baseline": majority_baseline,
        }

    return store, ""


# ── Public API ────────────────────────────────────────────────────────────────

def profile_data(results):
    """
    Profile the dataset before training.  Returns a summary dict.
    Does not train anything.
    """
    rows = _unique_labeled(results)
    total_raw = len(results)
    unique = len(rows)

    labels_all = [r[1] for r in rows]
    classes, counts = np.unique(labels_all, return_counts=True)
    class_dist = {str(c): int(n) for c, n in zip(classes, counts)}

    # Binary distribution
    binary_labels = _binarize(labels_all)
    bc, bn = np.unique(binary_labels, return_counts=True)
    binary_dist = {str(c): int(n) for c, n in zip(bc, bn)}

    # Feasibility checks
    can_binary = unique >= MIN_UNIQUE and all(n >= MIN_PER_CLASS for n in bn)
    can_multiclass = (
        unique >= MIN_UNIQUE
        and sum(1 for n in counts if n >= MIN_PER_CLASS) >= 2
    )

    return {
        "total_rows": total_raw,
        "unique_reviews": unique,
        "duplicates_removed": total_raw - unique,
        "class_distribution": class_dist,
        "binary_distribution": binary_dist,
        "min_per_class_required": MIN_PER_CLASS,
        "min_unique_required": MIN_UNIQUE,
        "can_train_binary": can_binary,
        "can_train_multiclass": can_multiclass,
        "label_source": LABEL_SOURCE_NOTE,
    }


def train_binary(results):
    """
    Train binary models (negative vs non-negative).
    Returns (store_dict_or_None, reason_string).
    """
    rows = _unique_labeled(results)
    if len(rows) < MIN_UNIQUE:
        return None, "Not enough data: %d unique reviews, need %d." % (len(rows), MIN_UNIQUE)

    texts = [r[0] for r in rows]
    labels = _binarize([r[1] for r in rows])
    return _train_one(texts, labels, "binary")


def train_multiclass(results):
    """
    Train multiclass models (positive / neutral / negative).
    Returns (store_dict_or_None, reason_string).
    """
    rows = _unique_labeled(results)
    if len(rows) < MIN_UNIQUE:
        return None, "Not enough data: %d unique reviews, need %d." % (len(rows), MIN_UNIQUE)

    texts = [r[0] for r in rows]
    labels = np.array([r[1] for r in rows])
    return _train_one(texts, labels, "multiclass")


def predict_with_model(store, model_key, text):
    """
    Predict sentiment for a single review text.
    store   : dict returned by train_binary / train_multiclass
    model_key : 'lr' or 'rf'
    Returns (result_dict, error_string).
    """
    text = str(text or "").strip()[:1000]
    if not text:
        return None, "Please provide a non-empty review text."
    if store is None:
        return None, "Model not trained yet. Call train_binary or train_multiclass first."
    if model_key not in store:
        return None, "Unknown model key '%s'. Use 'lr' or 'rf'." % model_key

    model = store[model_key]["model"]
    probs = model.predict_proba([text])[0]
    order = np.argsort(-probs)
    top = int(order[0])

    return {
        "task": store["task"],
        "model": model_key,
        "label": str(model.classes_[top]),
        "confidence": round(float(probs[top]), 3),
        "probabilities": {
            str(c): round(float(p), 3) for c, p in zip(model.classes_, probs)
        },
        "low_confidence": bool(probs[top] < LOW_CONFIDENCE_THRESHOLD),
        "label_source": LABEL_SOURCE_NOTE,
    }, ""


# ── Legacy compatibility (used by existing test_predictor.py) ─────────────────

def train_predictor(results):
    """
    Backward-compatible wrapper — returns (predictor_dict, reason).
    predictor_dict has keys expected by predict_sentiment().
    """
    store, reason = train_multiclass(results)
    if store is None:
        return None, reason
    lr = store["lr"]
    cv = lr["cv_metrics"]
    return {
        "model": lr["model"],
        "classes": store["classes"],
        "dropped_classes": store["dropped_classes"],
        "unique_reviews": store["unique_reviews"],
        "cv_folds": cv["cv_folds"],
        "cv_accuracy": cv["cv_accuracy"],
        "baseline_accuracy": lr["majority_baseline"],
        "method": lr["method"],
    }, ""


def predict_sentiment(predictor, text):
    """
    Backward-compatible wrapper.
    predictor: dict returned by train_predictor().
    """
    text = str(text or "").strip()[:1000]
    if not text:
        return None, "Please type a review."
    model = predictor["model"]
    probs = model.predict_proba([text])[0]
    order = np.argsort(-probs)
    top = int(order[0])
    return {
        "label": str(model.classes_[top]),
        "confidence": round(float(probs[top]), 3),
        "probabilities": {str(c): round(float(p), 3) for c, p in zip(model.classes_, probs)},
        "low_confidence": bool(probs[top] < LOW_CONFIDENCE_THRESHOLD),
    }, ""

